import { createHash } from 'node:crypto';
import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync, readdirSync, mkdirSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
const check = process.argv.includes('--check');
const skills = readdirSync('agent/skills')
  .sort()
  .map((name) => {
    const body = readFileSync(`agent/skills/${name}/SKILL.md`, 'utf8');
    const description = /^description: (.+)$/m.exec(body)?.[1];
    if (
      !/^[a-z]+(?:-[a-z]+)*$/.test(name) ||
      !body.startsWith(`---\nname: ${name}\n`) ||
      !description
    )
      throw new Error(`Invalid Skill ${name}`);
    for (const root of ['agent-seed/skills', 'features/verity-sandbox-toolkit/agent-seed/skills']) {
      const path = `${root}/${name}/SKILL.md`;
      if (check) {
        if (readFileSync(path, 'utf8') !== body) throw new Error(`Asset drift: ${path}`);
      } else {
        mkdirSync(`${root}/${name}`, { recursive: true });
        writeFileSync(path, body);
      }
    }
    return { name, description, body };
  });
const manifest =
  JSON.stringify(
    {
      version: 1,
      dispatcher: createHash('sha256').update(readFileSync('agent/cli/verity')).digest('hex'),
      files: Object.fromEntries(
        skills.map(({ name, body }) => [
          `${name}/SKILL.md`,
          createHash('sha256').update(body).digest('hex'),
        ]),
      ),
    },
    null,
    2,
  ) + '\n';
for (const root of ['agent-seed', 'features/verity-sandbox-toolkit/agent-seed']) {
  const path = `${root}/skills-manifest.json`;
  if (check) {
    if (readFileSync(path, 'utf8') !== manifest) throw new Error(`Skill manifest drift: ${path}`);
  } else writeFileSync(path, manifest);
}
const core = readdirSync('agent/prompt/core')
  .filter((name) => name.endsWith('.md'))
  .sort()
  .map((name) => readFileSync(join('agent/prompt/core', name), 'utf8'))
  .join('\n');
if (Buffer.byteLength(core) > 7200) throw new Error('Core exceeds 7200-byte regression budget');
const catalog = skills
  .map(({ name, description }) => `- ${name}: ${description.replace(/^Use /, '')}`)
  .join('\n');
if (Buffer.byteLength(catalog) > 2200)
  throw new Error('Catalog exceeds 2200-byte regression budget');
const output = `// Generated by scripts/sync-agent-assets.mjs. Edit agent/ sources instead.\n// prettier-ignore\nexport const AGENT_CORE_PROMPT = ${JSON.stringify(core)};\n// prettier-ignore\nexport const AGENT_SKILL_CATALOG = ${JSON.stringify(catalog)};\n// prettier-ignore\nexport const WIKI_MAINTENANCE_SKILL = ${JSON.stringify(skills.find(({ name }) => name === 'wiki-maintain').body)};\n// prettier-ignore\nexport const AGENT_SKILL_MANIFEST_HASH = ${JSON.stringify(createHash('sha256').update(manifest).digest('hex'))};\n`;
const target = 'packages/events/src/agent-assets.generated.ts';
if (check) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Generated prompt assets are stale');
} else writeFileSync(target, output);
for (const target of [
  'agent-seed/bin/verity',
  'features/verity-sandbox-toolkit/agent-seed/bin/verity',
]) {
  if (check) {
    if (readFileSync(target, 'utf8') !== readFileSync('agent/cli/verity', 'utf8'))
      throw new Error(`CLI drift: ${target}`);
  } else copyFileSync('agent/cli/verity', target);
}
